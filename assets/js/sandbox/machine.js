  function syncSystemFiles(sys) {
    if (!sys || !sys.fs) return sys;
    var passwd = [];
    Object.keys(sys.users).forEach(function (name) { passwd.push(sys.users[name]); });
    passwd.sort(function (a, b) { return a.uid - b.uid; });
    var passwdText = passwd.map(function (u) {
      return u.name + ':x:' + u.uid + ':' + u.gid + ':' + (u.gecos || u.name) + ':' + u.home + ':' + u.shell;
    }).join('\n') + '\n';

    var groupNames = Object.keys(sys.groups);
    var groups = groupNames.map(function (name) { return sys.groups[name]; });
    groups.sort(function (a, b) { return a.gid - b.gid; });
    var groupText = groups.map(function (g) {
      return g.name + ':x:' + g.gid + ':' + (g.members || []).join(',');
    }).join('\n') + '\n';

    var shadowText = passwd.map(function (u) {
      var hash = u.locked ? '!!' : (u.password || '$6$rhel$fieldbook');
      return u.name + ':' + hash + ':' + (u.lastChange === undefined ? 20000 : u.lastChange) + ':' +
        (u.minDays === undefined ? 0 : u.minDays) + ':' +
        (u.maxDays === undefined ? 99999 : u.maxDays) + ':' +
        (u.warnDays === undefined ? 7 : u.warnDays) + ':' +
        (u.inactiveDays === undefined ? -1 : u.inactiveDays) + ':' +
        (u.expireDays === undefined ? -1 : u.expireDays) + '::';
    }).join('\n') + '\n';

    if (sys.fs['/etc/passwd']) sys.fs['/etc/passwd'].content = passwdText;
    if (sys.fs['/etc/group']) sys.fs['/etc/group'].content = groupText;
    if (sys.fs['/etc/shadow']) sys.fs['/etc/shadow'].content = shadowText;
    return sys;
  }

