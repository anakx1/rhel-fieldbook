  function journal(sys, unit, priority, message, pid) {
    var date = new Date();
    var months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    function two(n) { return n < 10 ? '0' + n : String(n); }
    var ts = months[date.getMonth()] + ' ' + two(date.getDate()) + ' ' + two(date.getHours()) + ':' + two(date.getMinutes()) + ':' + two(date.getSeconds());
    sys.journal.push({
      ts: ts,
      unit: unit || 'systemd',
      pid: pid || 1,
      priority: priority === undefined ? 6 : priority,
      message: message || ''
    });
    if (sys.journal.length > 400) sys.journal.splice(0, sys.journal.length - 400);
    return sys.journal[sys.journal.length - 1];
  }

