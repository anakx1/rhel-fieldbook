  function execute(raw) {
    var cmd = raw.trim();
    if (!cmd) return;
    var prompt = el.prompt.textContent;
    appendCommand(prompt, cmd);
    state.history.push(cmd);
    state.historyIndex = state.history.length;

    if (cmd === 'clear') {
      el.log.innerHTML = '';
      return;
    }

    if (cmd === 'exit' || cmd === 'logout') {
      append('Sandbox session is persistent. Use the close button to hide the panel.', 'out amber');
      return;
    }

    if (/[>]/.test(cmd) && !/2>&1/.test(cmd)) {
      append('sandbox: this shell is read-only. Redirects are disabled here.', 'out amber');
      append('Run the command in your lab VM to write files.', 'out');
      return;
    }

    var result = runPipeline(cmd);
    appendOutput(result.out, result.error);
    updatePrompt();
  }

  function tokenize(line) {
    var re = /"([^"]*)"|'([^']*)'|(\S+)/g;
    var out = [];
    var m;
    while ((m = re.exec(line))) {
      out.push(m[1] !== undefined ? m[1] : m[2] !== undefined ? m[2] : m[3]);
    }
    return out;
  }

  function runPipeline(raw) {
    var stages = raw.split('|');
    var input = null;
    var last = { out: '', error: false };
    for (var i = 0; i < stages.length; i++) {
      var tokens = tokenize(stages[i].trim());
      if (!tokens.length) continue;
      last = runSingle(tokens, input);
      if (last.error) return last;
      input = last.out;
    }
    return last;
  }

  function runSingle(tokens, stdin) {
    var sudo = false;
    if (tokens[0] === 'sudo') {
      sudo = true;
      tokens = tokens.slice(1);
      if (!tokens.length) return { out: 'usage: sudo command [args]', error: true };
    }
    state.effectiveRoot = sudo;
    var cmd = tokens[0];
    var args = tokens.slice(1);
    var res;
    try {
      res = dispatch(cmd, args, stdin || '');
    } catch (err) {
      res = { out: 'sandbox: ' + err.message, error: true };
    }
    state.effectiveRoot = false;
    return res;
  }

