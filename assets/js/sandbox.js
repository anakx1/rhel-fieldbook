  function grep(args, stdin) {
    var flags = args.filter(function (a) { return a.charAt(0) === '-'; }).join('');
    var rest = args.filter(function (a) { return a.charAt(0) !== '-'; });
    var pattern = rest.shift();
    if (!pattern) return err('usage: grep [OPTION]... PATTERNS [FILE]...');
    var ignoreCase = flags.indexOf('i') !== -1;
    var invert = flags.indexOf('v') !== -1;
    var lineNum = flags.indexOf('n') !== -1;
    var count = flags.indexOf('c') !== -1;
    var recursive = flags.indexOf('r') !== -1;
    var text;
    if (rest.length) {
      if (recursive) {
        var base = normalize(rest[0]);
        var matches = [];
        Object.keys(FS).forEach(function (k) {
          if (k === base || k.indexOf(base + '/') === 0) {
            if (FS[k].dir) return;
            var result = grepText(pattern, FS[k].content || '', ignoreCase, invert, lineNum, count, k);
            if (result) matches.push(result);
          }
        });
        return ok(matches.join('\n'));
      }
      var p = normalize(rest[0]);
      var e = entry(p);
      if (!e) return err('grep: ' + rest[0] + ': No such file or directory');
      if (e.dir) return err('grep: ' + rest[0] + ': Is a directory');
      text = e.content || '';
    } else {
      text = stdin;
    }
    return ok(grepText(pattern, text, ignoreCase, invert, lineNum, count, ''));
  }

  function grepText(pattern, text, ignoreCase, invert, lineNum, count, prefix) {
    var re;
    try { re = new RegExp(pattern, ignoreCase ? 'i' : ''); }
    catch (e) { re = new RegExp(pattern.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), ignoreCase ? 'i' : ''); }
    var matches = [];
    text.split('\n').forEach(function (line, i) {
      var hit = re.test(line);
      if (invert) hit = !hit;
      if (hit) matches.push((prefix ? prefix + ':' : '') + (lineNum ? (i + 1) + ':' : '') + line);
    });
    if (count) return String(matches.length);
    return matches.join('\n');
  }

  function cutCmd(args, stdin) {
    var delim = ':';
    var fields = [1];
    for (var i = 0; i < args.length; i++) {
      if (args[i] === '-d' && args[i + 1]) { delim = args[i + 1]; i++; }
      else if (args[i].indexOf('-d') === 0 && args[i].length > 2) delim = args[i].slice(2);
      else if (args[i] === '-f' && args[i + 1]) { fields = args[i + 1].split(',').map(Number); i++; }
      else if (args[i].indexOf('-f') === 0 && args[i].length > 2) fields = args[i].slice(2).split(',').map(Number);
    }
    return ok(stdin.split('\n').map(function (line) {
      var parts = line.split(delim);
      return fields.map(function (f) { return parts[f - 1] || ''; }).join(delim);
    }).join('\n'));
  }

  function sortCmd(args, stdin) {
    var lines = stdin.split('\n');
    var numeric = false;
    var reverse = false;
    var unique = false;
    var human = false;
    args.forEach(function (arg) {
      if (arg.charAt(0) !== '-' || arg.length < 2) return;
      var flags = arg.slice(1);
      if (flags.indexOf('n') !== -1) numeric = true;
      if (flags.indexOf('r') !== -1) reverse = true;
      if (flags.indexOf('u') !== -1) unique = true;
      if (flags.indexOf('h') !== -1) human = true;
    });
    function humanNumber(line) {
      var match = String(line).trim().match(/^([0-9.]+)\s*([KMGTP]?)/i);
      if (!match) return 0;
      var units = { K: 1024, M: 1048576, G: 1073741824, T: 1099511627776, P: 1125899906842624 };
      var unit = (match[2] || '').toUpperCase();
      return parseFloat(match[1]) * (units[unit] || 1);
    }
    lines.sort(numeric || human ? function (a, b) {
      return (human ? humanNumber(a) : parseFloat(a)) - (human ? humanNumber(b) : parseFloat(b));
    } : function (a, b) { return a.localeCompare(b); });
    if (reverse) lines.reverse();
    if (unique) lines = lines.filter(function (l, i) { return i === 0 || l !== lines[i - 1]; });
    return ok(lines.join('\n'));
  }

  function uniqCmd(args, stdin) {
    var count = args.indexOf('-c') !== -1;
    var lines = stdin.split('\n');
    var out = [];
    for (var i = 0; i < lines.length; i++) {
      var n = 1;
      while (i + 1 < lines.length && lines[i + 1] === lines[i]) { n++; i++; }
      out.push((count ? String(n).padStart(7) + ' ' : '') + lines[i]);
    }
    return ok(out.join('\n'));
  }

  function wcCmd(args, stdin) {
    var lines = stdin.split('\n');
    if (stdin.endsWith('\n')) lines.pop();
    if (args.indexOf('-l') !== -1) return ok(String(lines.length));
    if (args.indexOf('-w') !== -1) return ok(String(stdin.trim() ? stdin.trim().split(/\s+/).length : 0));
    if (args.indexOf('-c') !== -1) return ok(String(stdin.length));
    return ok(lines.length + ' ' + (stdin.trim() ? stdin.trim().split(/\s+/).length : 0) + ' ' + stdin.length);
  }

