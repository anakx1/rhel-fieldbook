  function ls(args, stdin) {
    var flags = args.filter(function (a) { return a.charAt(0) === '-' && a.length > 1; }).join('');
    var paths = args.filter(function (a) { return a.charAt(0) !== '-'; });
    if (!paths.length) paths = ['.'];
    var long = flags.indexOf('l') !== -1;
    var all = flags.indexOf('a') !== -1;
    var showContext = flags.indexOf('Z') !== -1;
    var dirOnly = flags.indexOf('d') !== -1;
    var lines = [];
    paths.forEach(function (p) {
      var path = normalize(p);
      var e = entry(path);
      if (!e) { lines.push('ls: cannot access \'' + p + '\': No such file or directory'); return; }
      if (!e.dir || dirOnly) {
        lines.push(formatEntry(path, e, long, showContext));
        return;
      }
      if (paths.length > 1) { if (lines.length) lines.push(''); lines.push(displayPath(path) + ':'); }
      children(path).forEach(function (child) {
        var name = child.split('/').pop();
        if (!all && name.charAt(0) === '.') return;
        lines.push(formatEntry(child, FS[child], long, showContext));
      });
    });
    return ok(lines.join('\n'));
  }

  function formatEntry(path, e, long, showContext) {
    var name = displayPath(path);
    if (!long) return name + (e.dir ? '/' : '');
    var ctx = showContext ? ' ' + contextFor(path, e) : '';
    return e.mode + '. 1 ' + pad(e.owner, 8) + pad(e.group, 8) + pad(sizeOf(e), 6) + 'Nov 14 09:12 ' + name + (e.dir ? '/' : '') + ctx;
  }

